#!/usr/bin/env python3
"""Builds THIRD-PARTY-NOTICES.txt: the licenses of everything Dokuwu ships.

Run from the repository root after changing a dependency:

    cd frontend && npm ci && cd ..
    python scripts/generate_third_party_notices.py

Needs cargo (to read the Rust dependency graph for Windows) and the installed
npm packages (to read their license files). The output is written to
THIRD-PARTY-NOTICES.txt and copied, with LICENSE, to frontend/src/assets/legal/,
which the Licenses page in Settings shows (a test keeps the copies in step). Dev and build tools are not listed: they are
not part of what is installed.
"""
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD-PARTY-NOTICES.txt"
LEGAL_DIR = ROOT / "frontend" / "src" / "assets" / "legal"
OUT_APP = LEGAL_DIR / "THIRD-PARTY-NOTICES.txt"
WINDOWS = "x86_64-pc-windows-msvc"

# Rust programs that are installed: the app (which links dokuwu-core) and the
# Edit Content worker.
RUST_ROOTS = [
    ROOT / "frontend" / "src-tauri" / "Cargo.toml",
    ROOT / "native" / "edit-content-engine" / "Cargo.toml",
]
# MuPDF has its own section in the file.
OWN_PACKAGES = {"app", "dokuwu-core", "edit-content-engine", "mupdf", "mupdf-sys"}

LICENSE_FILE = re.compile(r"^(licen[cs]es?|copying|notice|unlicense|copyright)([-._].*)?$", re.I)
RULE = "=" * 78
THIN = "-" * 78

HEADER = """\
Dokuwu third-party notices
{rule}

Dokuwu is free software under the GNU Affero General Public License, version 3
or later (see LICENSE). It is built from the components below, which keep their
own licenses and copyright notices. They are reproduced here as those licenses
require. Source code of Dokuwu: https://github.com/hubble99/pdf-manager

Contents
  1. MuPDF and the libraries built into it
  2. PDFium (Edit Content)
  3. Fonts shipped with Dokuwu
  4. Rust crates
  5. npm packages

This file is generated by scripts/generate_third_party_notices.py.
"""

