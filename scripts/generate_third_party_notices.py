URW = """\
Base 14 PDF fonts (Nimbus Sans, Nimbus Roman, Nimbus Mono PS, Standard Symbols,
Dingbats), (c) URW++ Design & Development, shipped inside MuPDF to draw text
set in the standard PDF fonts. They are distributed with MuPDF/Ghostscript
under the GNU AGPL version 3.

DejaVu Sans Mono (native/dokuwu-core/assets/fonts), used for the text under
barcodes, under the Bitstream Vera and DejaVu font license:
"""

PDFIUM = """\
PDFium (https://pdfium.googlesource.com/pdfium), (c) The PDFium Authors.
  License: BSD 3-Clause (and Apache 2.0 for parts). Dokuwu uses the prebuilt
  library from https://github.com/bblanchon/pdfium-binaries, release
  chromium/8035, in the separate Edit Content process (pdfium.dll). The
  library bundles the components below; their license files follow.
"""


def read_text(path):
    return path.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n").strip("\n")


def license_files(directory):
    found = []
    if not directory.is_dir():
        return found
    for entry in sorted(directory.iterdir()):
        if entry.is_file() and LICENSE_FILE.match(entry.name):
            found.append(entry)
        elif entry.is_dir() and entry.name.lower() in ("licenses", "license", "licences"):
            found.extend(f for f in sorted(entry.iterdir()) if f.is_file())
    return found


def normal_closure(metadata):
    """Packages reachable through normal (non-dev, non-build) dependencies."""
    nodes = {n["id"]: n for n in metadata["resolve"]["nodes"]}
    seen, stack = set(), [metadata["resolve"]["root"]]
    while stack:
        pid = stack.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]):
                stack.append(dep["pkg"])
    return seen


def rust_packages():
    found = {}
    for manifest in RUST_ROOTS:
        raw = subprocess.run(
            ["cargo", "metadata", "--locked", "--format-version", "1",
             "--filter-platform", WINDOWS, "--manifest-path", str(manifest)],
            check=True, capture_output=True, text=True,
        ).stdout
        meta = json.loads(raw)
        by_id = {p["id"]: p for p in meta["packages"]}
        for pid in normal_closure(meta):
            pkg = by_id[pid]
            if pkg["name"] in OWN_PACKAGES:
                continue
            found[(pkg["name"], pkg["version"])] = {
                "name": pkg["name"],
                "version": pkg["version"],
                "license": pkg.get("license") or "see source",
                "url": pkg.get("repository") or pkg.get("homepage") or f"https://crates.io/crates/{pkg['name']}",
                "files": license_files(Path(pkg["manifest_path"]).parent),
            }
    return sorted(found.values(), key=lambda p: (p["name"], p["version"]))


def npm_packages():
    lock = json.loads((ROOT / "frontend" / "package-lock.json").read_text(encoding="utf-8"))
    found = []
    for path, entry in lock["packages"].items():
        if not path or entry.get("dev") or entry.get("devOptional") or entry.get("optional"):
            continue
        name = path.split("node_modules/")[-1]
        directory = ROOT / "frontend" / path
        found.append({
            "name": name,
            "version": entry["version"],
            "license": entry.get("license") or "see source",
            "url": f"https://www.npmjs.com/package/{name}",
            "files": license_files(directory),
        })
        if not directory.is_dir():
            sys.exit(f"{path} is not installed; run npm ci in frontend first")
    return sorted(found, key=lambda p: (p["name"], p["version"]))


def grouped(packages):
    """One entry per distinct license text, listing every package that carries it."""
    groups, without = {}, []
    for pkg in packages:
        texts = {read_text(f) for f in pkg["files"]}
        texts.discard("")
        if not texts:
            without.append(pkg)
            continue
        for text in texts:
            key = hashlib.sha256(text.encode()).hexdigest()
            group = groups.setdefault(key, {"text": text, "packages": []})
            if pkg not in group["packages"]:
                group["packages"].append(pkg)
    ordered = sorted(groups.values(), key=lambda g: (-len(g["packages"]), g["packages"][0]["name"]))
    return ordered, without


def render_packages(title, packages):
    out = [RULE, title, RULE, ""]
    groups, without = grouped(packages)
    for g in groups:
        for pkg in g["packages"]:
            out.append(f"{pkg['name']} {pkg['version']} ({pkg['license']}) - {pkg['url']}")
        out.append("")
        out.append(g["text"])
        out.append("")
        out.append(THIN)
        out.append("")
    if without:
        out.append("These packages ship no license file; their license is named below and the")
        out.append("full text is at https://spdx.org/licenses/.")
        out.append("")
        for pkg in without:
            out.append(f"{pkg['name']} {pkg['version']} ({pkg['license']}) - {pkg['url']}")
        out.append("")
    return out


def main():
    out = [HEADER.format(rule=RULE)]
    out += [RULE, "1. MuPDF and the libraries built into it", RULE, "", MUPDF, ""]
    out += [RULE, "2. PDFium (Edit Content)", RULE, "", PDFIUM]
    notices = ROOT / "native" / "edit-content-engine" / "notices"
    for f in [notices / "LICENSE"] + sorted((notices / "licenses").iterdir()):
        out += [THIN, f"PDFium notice: {f.relative_to(notices).as_posix()}", THIN, read_text(f), ""]
    out += [RULE, "3. Fonts shipped with Dokuwu", RULE, "", URW]
    out += [read_text(ROOT / "native" / "dokuwu-core" / "assets" / "fonts" / "DejaVuSansMono-LICENSE.txt"), ""]
    out += render_packages("4. Rust crates", rust_packages())
    out += render_packages("5. npm packages", npm_packages())
    text = "\n".join(out).rstrip("\n") + "\n"
    OUT.write_text(text, encoding="utf-8", newline="\n")
    LEGAL_DIR.mkdir(parents=True, exist_ok=True)
    OUT_APP.write_text(text, encoding="utf-8", newline="\n")
    (LEGAL_DIR / "LICENSE.txt").write_text(read_text(ROOT / "LICENSE") + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(text) // 1024} KB)")


if __name__ == "__main__":
    main()
