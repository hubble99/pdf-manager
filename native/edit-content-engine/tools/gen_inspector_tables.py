"""Writes the data tables of the native resource inspector.

The Python inspector gets these from fontTools (Adobe Glyph List), the codecs
(WinAnsi, MacRoman) and pypdf (PDFDocEncoding). The Rust inspector carries them
as data so both agree. Run from the repository root with the backend's venv:

    python native/edit-content-engine/tools/gen_inspector_tables.py
"""
from pathlib import Path

from fontTools.agl import LEGACY_AGL2UV
from pypdf._codecs.pdfdoc import _pdfdoc_encoding

OUT = Path(__file__).resolve().parents[1] / "src/native_inspector/data"


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    lines = []
    for name in sorted(LEGACY_AGL2UV):
        lines.append(name + " " + ",".join(f"{cp:X}" for cp in LEGACY_AGL2UV[name]))
    (OUT / "agl.txt").write_text("\n".join(lines) + "\n", encoding="ascii")

    def codec_row(codec: str) -> list:
        row = []
        for value in range(0x20, 0x100):
            try:
                row.append(ord(bytes([value]).decode(codec)))
            except UnicodeDecodeError:
                row.append(0)
        return row

    def fmt(name: str, values: list, per_line: int = 12) -> str:
        body = ""
        for i in range(0, len(values), per_line):
            body += "    " + ", ".join(f"0x{v:04X}" for v in values[i:i + per_line]) + ",\n"
        return f"pub const {name}: [u32; {len(values)}] = [\n{body}];\n\n"

    pdfdoc = [0xFFFD if c == "�" else ord(c) for c in _pdfdoc_encoding]
    assert len(pdfdoc) == 256
    text = "// Generated by tools/gen_inspector_tables.py; do not edit.\n\n"
    text += "/// Code points of bytes 0x20..=0xFF in Python's `cp1252` codec; 0 where undefined.\n"
    text += fmt("WIN_ANSI", codec_row("cp1252"))
    text += "/// Code points of bytes 0x20..=0xFF in Python's `mac_roman` codec.\n"
    text += fmt("MAC_ROMAN", codec_row("mac_roman"))
    text += "/// pypdf's PDFDocEncoding table; 0xFFFD marks an undefined byte.\n"
    text += fmt("PDF_DOC", pdfdoc)
    (OUT / "encodings.rs").write_text(text, encoding="ascii")
    print(len(lines), "glyph names")


if __name__ == "__main__":
    main()
