<#
.SYNOPSIS
  Builds the Dokuwu MSIX package for Microsoft Store submission.

.DESCRIPTION
  Takes the app files from the Tauri MSI, adds the Store images from
  docs\brand\store\Assets, fills AppxManifest.template.xml, indexes the
  resources with makepri and packs with makeappx. The .msix is UNSIGNED:
  Partner Center signs it on upload.

  -TestSign also makes a throwaway self-signed copy in test-cert\ for a local
  sideload test. Never upload that copy. Nothing in test-cert\ is committed.

.EXAMPLE
  .\build-msix.ps1 -Version 2.0.0.0 `
                   -IdentityName "hubble99.Dokuwu" `
                   -Publisher "CN=386DE0B9-C4EC-460D-9AD6-816F1A61442D" `
                   -PublisherDisplayName "hubble99" `
                   -Msi C:\t\release\bundle\msi\Dokuwu_2.0.0_x64_en-US.msi
#>
param(
  [Parameter(Mandatory)] [string] $Version,
  [Parameter(Mandatory)] [string] $IdentityName,
  [Parameter(Mandatory)] [string] $Publisher,
  [Parameter(Mandatory)] [string] $PublisherDisplayName,
  [Parameter(Mandatory)] [string] $Msi,
  [string] $DisplayName = "Dokuwu",
  [switch] $TestSign
)

$ErrorActionPreference = "Stop"
$Here = $PSScriptRoot
$Repo = (Resolve-Path (Join-Path $Here "..\..")).Path

if ($Version -notmatch '^\d+\.\d+\.\d+\.0$') { throw "Version must be X.Y.Z.0 (the Store reserves the last number)." }
if (-not (Test-Path $Msi)) { throw "MSI not found: $Msi" }

# Windows SDK tools: the newest installed version.
$SdkBin = Get-ChildItem "C:\Program Files (x86)\Windows Kits\10\bin" -Directory |
  Where-Object { $_.Name -match '^10\.' -and (Test-Path (Join-Path $_.FullName "x64\makeappx.exe")) } |
  Sort-Object { [version]$_.Name } -Descending | Select-Object -First 1
if (-not $SdkBin) { throw "Windows SDK (makeappx, makepri) not found." }
$Sdk = Join-Path $SdkBin.FullName "x64"
$MakeAppx = Join-Path $Sdk "makeappx.exe"
$MakePri = Join-Path $Sdk "makepri.exe"
$SignTool = Join-Path $Sdk "signtool.exe"

$Work = Join-Path $Here "build"
$Layout = Join-Path $Work "layout"
if (Test-Path $Work) { Remove-Item -Recurse -Force $Work }
New-Item -ItemType Directory -Force $Layout | Out-Null

# 1. App files: exactly what the MSI installs.
$extract = Join-Path $Work "msi"
Write-Host "Extracting $Msi"
$p = Start-Process msiexec -ArgumentList "/a `"$Msi`" /qn TARGETDIR=`"$extract`"" -Wait -PassThru
if ($p.ExitCode -ne 0) { throw "msiexec /a failed ($($p.ExitCode))" }
$SourceDir = Get-ChildItem (Join-Path $extract "PFiles") -Directory | Select-Object -First 1 -ExpandProperty FullName
foreach ($f in "app.exe", "edit-content\edit-content-engine.exe", "edit-content\pdfium.dll",
               "legal\LICENSE", "legal\THIRD-PARTY-NOTICES.txt") {
  if (-not (Test-Path (Join-Path $SourceDir $f))) { throw "Missing $f in $SourceDir" }
}
Copy-Item -Recurse (Join-Path $SourceDir "*") $Layout

# 2. Store images, named the way MSIX expects (generated by scripts\brand\generate_brand_assets.py).
Copy-Item -Recurse (Join-Path $Repo "docs\brand\store\Assets") (Join-Path $Layout "Assets")

# 3. Manifest
$xml = Get-Content -Raw -Encoding UTF8 (Join-Path $Here "AppxManifest.template.xml")
$esc = { param($s) [System.Security.SecurityElement]::Escape($s) }
$xml = $xml.Replace("{{IDENTITY_NAME}}", (& $esc $IdentityName)).
            Replace("{{PUBLISHER}}", (& $esc $Publisher)).
            Replace("{{PUBLISHER_DISPLAY_NAME}}", (& $esc $PublisherDisplayName)).
            Replace("{{DISPLAY_NAME}}", (& $esc $DisplayName)).
            Replace("{{VERSION}}", $Version)
[IO.File]::WriteAllText((Join-Path $Layout "AppxManifest.xml"), $xml, (New-Object Text.UTF8Encoding $false))

# 4. Resource index (needed for the scale and target-size image variants)
$priConfig = Join-Path $Work "priconfig.xml"
& $MakePri createconfig /cf $priConfig /dq en-US /pv 10.0.0 /o | Out-Null
if ($LASTEXITCODE) { throw "makepri createconfig failed" }
& $MakePri new /pr $Layout /cf $priConfig /mn (Join-Path $Layout "AppxManifest.xml") /of (Join-Path $Layout "resources.pri") /o | Out-Null
if ($LASTEXITCODE) { throw "makepri new failed" }

# 5. Pack
$name = "Dokuwu_${Version}_x64"
$out = Join-Path $Here "$name.msix"
& $MakeAppx pack /d $Layout /p $out /o | Select-Object -Last 1 | Out-Host
if ($LASTEXITCODE) { throw "makeappx pack failed" }
Write-Host "Store package (unsigned): $out"

# 6. Optional local test signing (never upload this one)
if ($TestSign) {
  $certDir = Join-Path $Here "test-cert"
  New-Item -ItemType Directory -Force $certDir | Out-Null
  $cert = New-SelfSignedCertificate -Type Custom -Subject $Publisher -KeyUsage DigitalSignature `
    -FriendlyName "Dokuwu MSIX local test" -CertStoreLocation "Cert:\CurrentUser\My" `
    -TextExtension @("2.5.29.37={text}1.3.6.1.5.5.7.3.3", "2.5.29.19={text}") -NotAfter (Get-Date).AddDays(30)
  $pwd = ConvertTo-SecureString -String "localtest" -Force -AsPlainText
  $pfx = Join-Path $certDir "dokuwu-test.pfx"
  Export-PfxCertificate -Cert $cert -FilePath $pfx -Password $pwd | Out-Null
  Export-Certificate -Cert $cert -FilePath (Join-Path $certDir "dokuwu-test.cer") | Out-Null
  $testOut = Join-Path $certDir "$name.TEST-SIGNED.msix"
  Copy-Item $out $testOut -Force
  & $SignTool sign /fd SHA256 /f $pfx /p localtest $testOut | Out-Host
  if ($LASTEXITCODE) { throw "signtool failed" }
  Write-Host "Test-signed copy (local only): $testOut"
}
